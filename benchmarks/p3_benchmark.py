#!/usr/bin/env python3
"""P3: Weighted cache hit rate benchmark.

FINDINGS (2026-10-02):
- Proxy is NOT the bottleneck: direct vLLM shows identical cache behavior.
- vLLM hybrid-Mamba model caps reusable prefix at ~1664 tokens for ~2.5k-token
  prompts -> per-response hit rate plateaus ~60-65%.
- vLLM global rate on real Goose traffic (50k+ tok): 83.5%.
- To reach >90%: increase --kv-cache-memory-bytes and review mamba cache
  alignment in vllm-serve.fish. See benchmarks/p3_results.json.
"""
import json, time, statistics, urllib.request

PROXY = "http://127.0.0.1:9201/v1/chat/completions"
MODEL = "Qwen3.8-27B"
N_SESSIONS = 20
N_TURNS_PER_SESSION = 10
MAX_TOKENS = 16

# Build a realistic ~2000 token system prompt
BASE = (
    "You are a senior software engineer assistant running inside the ctxgate-proxy "
    "system. The proxy manages a rolling context window for local LLM inference on "
    "a single GPU. Your job is to help with Python, Rust, and systems programming tasks. "
    "You should be concise, precise, and practical. When explaining code, show the "
    "relevant snippet and explain the key design decisions. Avoid filler phrases. "
    "If the user asks about architecture, discuss trade-offs explicitly. "
    "You are connected to a PostgreSQL database for persistent memory and a "
    "background worker that extracts facts from conversations. "
    "The system uses a frozen-prefix contract: the first three messages (system, "
    "seed user, seed assistant) are immutable for the session lifetime. "
    "KV-cache reuse depends on byte-identical prefixes being sent to vLLM. "
    "When context exceeds the token budget, the oldest messages are trimmed "
    "and a summary is generated by a smaller model. "
    "You should acknowledge when context has been compacted and continue naturally. "
)
# Repeat to reach ~2000 tokens (each BASE is ~150 tokens, need ~13 repeats)
SYSTEM_PROMPT = BASE * 14  # ~2100 tokens

SEED_USER = "I'm working on a context proxy for local LLM inference. I need help with the Python implementation. The system manages rolling context windows, KV-cache reuse, and background memory extraction. Let's start with the core message handling logic."
SEED_ASSISTANT = "Great, let's dive in. The core of the proxy is the message pipeline: receive messages, tokenize to check budget, trim oldest if over cap, freeze the seed pair for prefix stability, and forward to vLLM. I'll walk through each stage."

TOPICS = [
    "How does the trim_context function decide which messages to remove? Walk me through the algorithm.",
    "Explain the frozen-prefix contract. Why are the first 3 messages immutable and what happens if they change?",
    "How does the proxy track token counts without a full tokenizer? Is there an approximation?",
    "What happens when a session's context exceeds the max model length? Walk through the compaction flow.",
    "How does the prefix fingerprint work? What hash is used and what does it cover?",
    "Explain the continuation logic. What happens when vLLM returns finish_reason='length'?",
    "How does the streaming path differ from the non-streaming path in terms of token accounting?",
    "What is the role of the background worker in the memory extraction pipeline?",
    "How does the proxy handle tool calls? Walk through the sanitize_tool_calls function.",
    "Explain the session key construction. How does it combine x_session_id with the content fingerprint?",
]

def post_proxy(messages):
    body = {
        "model": MODEL,
        "messages": messages,
        "max_tokens": MAX_TOKENS,
        "temperature": 0.0,
        "stream": False,
    }
    req = urllib.request.Request(
        PROXY, data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"}, method="POST",
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            data = json.load(r)
        lat = time.time() - t0
        usage = data.get("usage", {})
        prompt_tok = usage.get("prompt_tokens", 0)
        comp_tok = usage.get("completion_tokens", 0)
        ptd = usage.get("prompt_tokens_details", {})
        cached_tok = ptd.get("cached_tokens", 0)
        return {
            "ok": True, "lat": lat, "prompt": prompt_tok, "completion": comp_tok,
            "cached": cached_tok,
            "cached_pct": round(100 * cached_tok / max(1, prompt_tok), 1),
        }
    except Exception as e:
        return {"ok": False, "lat": time.time() - t0, "err": str(e)}

def run():
    all_results = []
    session_results = []

    print("=== P3 Weighted Cache Hit Rate Benchmark ===")
    print(f"Sessions: {N_SESSIONS}  Turns/session: {N_TURNS_PER_SESSION}  Total: {N_SESSIONS * N_TURNS_PER_SESSION}")
    print(f"System prompt: ~{len(SYSTEM_PROMPT)} chars")
    print(f"Model: {MODEL}  Proxy: {PROXY}")
    print()

    for s in range(N_SESSIONS):
        topic_offset = s % len(TOPICS)
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": SEED_USER},
            {"role": "assistant", "content": SEED_ASSISTANT},
        ]

        session_cached = 0
        session_prompt = 0
        session_lats = []
        ok_turns = 0

        for t in range(N_TURNS_PER_SESSION):
            q = TOPICS[(topic_offset + t) % len(TOPICS)]
            filler = f" [turn {t+1}]"
            messages.append({"role": "user", "content": q + filler})

            r = post_proxy(messages)
            if not r["ok"]:
                print(f"  S{s:2d} T{t}: ERR {r.get('err','?')[:60]}")
                break

            session_cached += r["cached"]
            session_prompt += r["prompt"]
            session_lats.append(r["lat"])
            ok_turns += 1
            all_results.append({
                "session": s, "turn": t, "prompt": r["prompt"],
                "cached": r["cached"], "cached_pct": r["cached_pct"], "lat": r["lat"],
            })

            # Add short assistant reply to grow context
            messages.append({
                "role": "assistant",
                "content": f"Good question on turn {t+1}. " + q[:60] + " The key insight is in the block-level prefix matching.",
            })

        s_pct = round(100 * session_cached / max(1, session_prompt), 1)
        avg_lat = statistics.mean(session_lats) if session_lats else 0
        session_results.append({
            "session": s, "turns": ok_turns,
            "prompt_tokens": session_prompt, "cached_tokens": session_cached,
            "hit_rate_pct": s_pct, "avg_lat": round(avg_lat, 2),
        })
        print(f"  S{s:2d}: {ok_turns:2d}t {session_prompt:6d}p {session_cached:6d}c {s_pct:5.1f}% {avg_lat:.2f}s")

    total_prompt = sum(r["prompt"] for r in all_results)
    total_cached = sum(r["cached"] for r in all_results)
    overall = total_cached / max(1, total_prompt)
    lats = [r["lat"] for r in all_results]
    pcts = [r["cached_pct"] for r in all_results]

    print(f"\n{'='*50}")
    print(f"TOTAL REQUESTS:    {len(all_results)}")
    print(f"TOTAL PROMPT TOK:  {total_prompt}")
    print(f"TOTAL CACHED TOK:  {total_cached}")
    print(f"WEIGHTED HIT RATE: {overall*100:.2f}%")
    print(f"TARGET:            90.00%")
    print(f"MET TARGET:        {'YES' if overall >= 0.90 else 'NO'}")
    print(f"\nPer-request: mean={statistics.mean(pcts):.1f}% med={statistics.median(pcts):.1f}% min={min(pcts):.1f}% max={max(pcts):.1f}%")
    print(f"Latency:   p50={statistics.median(lats):.2f}s p95={sorted(lats)[max(0,int(len(lats)*0.95)-1)]:.2f}s max={max(lats):.2f}s")

    cold = [r for r in all_results if r["turn"] == 0]
    warm = [r for r in all_results if r["turn"] >= 3]
    cold_rate = sum(r["cached"] for r in cold) / max(1, sum(r["prompt"] for r in cold))
    warm_rate = sum(r["cached"] for r in warm) / max(1, sum(r["prompt"] for r in warm))
    print(f"Cold (t0):  {cold_rate*100:.1f}% ({len(cold)} reqs)")
    print(f"Warm (t3+): {warm_rate*100:.1f}% ({len(warm)} reqs)")

    out = {
        "benchmark": "P3_weighted_cache_hit_rate_v2",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "n_sessions": N_SESSIONS, "n_turns": N_TURNS_PER_SESSION,
        "total_requests": len(all_results),
        "total_prompt_tokens": total_prompt,
        "total_cached_tokens": total_cached,
        "weighted_hit_rate": round(overall, 4),
        "target": 0.90, "met_target": overall >= 0.90,
        "cold_rate": round(cold_rate, 4), "warm_rate": round(warm_rate, 4),
        "sessions": session_results,
    }
    with open("/home/pawelw/ctxproxy/benchmarks/p3_results.json", "w") as f:
        json.dump(out, f, indent=2)
    print(f"\nSaved to benchmarks/p3_results.json")

if __name__ == "__main__":
    run()
